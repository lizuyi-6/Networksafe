param(
    [string]$Source = "manuscript.tex",
    [string]$Output = "submission.tex"
)

$ErrorActionPreference = "Stop"

function Expand-TexFile {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path,
        [System.Collections.Generic.HashSet[string]]$Stack
    )

    $resolved = (Resolve-Path -Path $Path).Path
    if ($Stack.Contains($resolved)) {
        throw "Circular \\input detected while expanding $resolved"
    }

    $null = $Stack.Add($resolved)
    $directory = Split-Path -Path $resolved -Parent
    $builder = New-Object System.Text.StringBuilder

    foreach ($line in Get-Content -Path $resolved) {
        if ($line -match '^\s*\\input\{([^}]+)\}\s*$') {
            $target = $Matches[1]
            if (-not [System.IO.Path]::GetExtension($target)) {
                $target = "$target.tex"
            }

            $targetPath = Join-Path -Path $directory -ChildPath $target
            [void]$builder.AppendLine("% BEGIN INPUT: $target")
            [void]$builder.Append((Expand-TexFile -Path $targetPath -Stack $Stack))
            [void]$builder.AppendLine("% END INPUT: $target")
        } else {
            [void]$builder.AppendLine($line)
        }
    }

    $null = $Stack.Remove($resolved)
    return $builder.ToString()
}

$sourcePath = Join-Path -Path $PSScriptRoot -ChildPath $Source
$outputPath = Join-Path -Path $PSScriptRoot -ChildPath $Output
$stack = [System.Collections.Generic.HashSet[string]]::new()
$content = Expand-TexFile -Path $sourcePath -Stack $stack
$header = @(
    "% Auto-generated by build-submission.ps1.",
    "% Edit manuscript.tex and sections/*, then rerun this script.",
    ""
) -join [Environment]::NewLine

Set-Content -Path $outputPath -Value ($header + $content) -Encoding utf8
Write-Output "Wrote $outputPath"
