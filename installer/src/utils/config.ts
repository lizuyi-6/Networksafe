import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { promisify } from 'util';

const writeFile = promisify(fs.writeFile);
const chmod = promisify(fs.chmod);

export interface AetherGuardConfig {
  jwtSecret: string;
  auditLogSecret: string;
  encryptionKey: string;
  encryptionSalt: string;
  deviceCommandSecret: string;
  adminEmail: string;
  adminPassword: string;
  httpPort: number;
  httpsPort: number;
  backendPort: number;
  allowedOrigins: string;
  redisPassword: string;
}

/**
 * SECURITY FIX (audit 2026-08, DP-003): both generators previously used
 * Math.random() — a predictable PRNG — for production secrets (JWT signing,
 * audit-log signing, agent-secret encryption key/salt, device command
 * signing, Redis password). Math.random() is seed-recoverable and never
 * suitable for cryptographic material; an attacker who can observe enough
 * output (or the PRNG state) could predict subsequently generated secrets.
 * Both now draw from crypto.randomBytes, and the alphanumeric generator
 * uses rejection sampling to avoid modulo bias.
 */
export function generateSecret(length = 32): string {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  // 256 % 62 === 8: reject the top 8 byte values so modulo mapping stays uniform.
  const rejectionThreshold = 256 - (256 % chars.length);
  const out: string[] = [];
  while (out.length < length) {
    const buf = crypto.randomBytes(length);
    for (let i = 0; i < buf.length && out.length < length; i += 1) {
      if (buf[i] >= rejectionThreshold) {
        continue;
      }
      out.push(chars.charAt(buf[i] % chars.length));
    }
  }
  return out.join('');
}

export function generateHexSecret(length = 32): string {
  return crypto.randomBytes(length).toString('hex');
}

export function buildEnvContent(config: AetherGuardConfig): string {
  return `# ─────────────────────────────────────────────────────────────
# AetherGuard Environment Configuration
# Generated by aetherguard-cli
# ─────────────────────────────────────────────────────────────

# Required: Redis password
REDIS_PASSWORD=${config.redisPassword}

# Required: JWT signing secret
JWT_SECRET=${config.jwtSecret}

# Required: Audit log signing secret
AUDIT_LOG_SECRET=${config.auditLogSecret}

# Required: Encryption key for agent secrets
ENCRYPTION_KEY=${config.encryptionKey}

# Required: Encryption salt for agent secrets
ENCRYPTION_SALT=${config.encryptionSalt}

# Required: Device command signing secret
DEVICE_COMMAND_SECRET=${config.deviceCommandSecret}

# Admin credentials
ADMIN_EMAIL=${config.adminEmail}
ADMIN_PASSWORD=${config.adminPassword}

# Ports
FRONTEND_PORT=${config.httpPort}
BACKEND_PORT=${config.backendPort}
REDIS_PORT=6379

# CORS origins
ALLOWED_ORIGINS=${config.allowedOrigins}

# Optional: API keys
VALID_API_KEYS=
DEVICE_API_KEYS=

# Optional: rate limit engine
API_RATE_LIMIT_ENGINE=legacy

# Production mode
NODE_ENV=production
DISABLE_REDIS=false
`;
}

export async function writeEnvFile(config: AetherGuardConfig, targetDir: string): Promise<void> {
  const envPath = path.join(targetDir, '.env');
  const content = buildEnvContent(config);
  await writeFile(envPath, content, { mode: 0o600 });
}

export function parseEnvFile(envPath: string): Record<string, string> {
  const result: Record<string, string> = {};
  if (!fs.existsSync(envPath)) return result;

  const content = fs.readFileSync(envPath, 'utf-8');
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIndex = trimmed.indexOf('=');
    if (eqIndex === -1) continue;
    const key = trimmed.substring(0, eqIndex).trim();
    const value = trimmed.substring(eqIndex + 1).trim();
    result[key] = value;
  }
  return result;
}
