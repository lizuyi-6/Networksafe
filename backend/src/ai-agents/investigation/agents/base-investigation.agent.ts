/**
 * Base Investigation Agent
 *
 * Abstract base class for all investigation agents.
 * Extends the existing BaseAgent pattern with investigation-specific capabilities.
 */

import { InvestigationContext, InvestigationAgentType } from '../types';
import { AgentConfig, MessageBus, BaseAgent } from '../../core';
import type { AgentMessage } from '../../core/types';
import type { AnalysisResult, ModelResponse, TrafficContext } from '../../core/types';
import { distributionFromVerdict } from '../../core/scoring';

export abstract class BaseInvestigationAgent extends BaseAgent {
  protected agentType: InvestigationAgentType;
  protected expertise: string[];
  private processedMessageIds: Set<string> = new Set();
  private maxProcessedMessages: number = 10000;

  constructor(config: AgentConfig, messageBus: MessageBus, agentType: InvestigationAgentType, expertise: string[]) {
    super(config, messageBus);
    this.agentType = agentType;
    this.expertise = expertise;
  }

  private isMessageProcessed(messageId: string): boolean {
    return this.processedMessageIds.has(messageId);
  }

  private markMessageProcessed(messageId: string): void {
    if (this.processedMessageIds.size >= this.maxProcessedMessages) {
      const iterator = this.processedMessageIds.values();
      const oldest = iterator.next().value;
      if (oldest !== undefined) {
        this.processedMessageIds.delete(oldest);
      }
    }
    this.processedMessageIds.add(messageId);
  }

  protected isOwnMessage(message: AgentMessage): boolean {
    return message.from === this.identity.role;
  }

  /**
   * Core investigation analysis method implemented by subclasses.
   */
  protected abstract analyzeInvestigation(context: InvestigationContext): Promise<any>;

  /**
   * BaseAgent-compatible analyze method.
   * Supports investigation-native input and gracefully adapts traffic input.
   */
  public async analyze(context: TrafficContext): Promise<AnalysisResult>;
  public async analyze(context: InvestigationContext): Promise<any>;
  public async analyze(context: TrafficContext | InvestigationContext): Promise<AnalysisResult | any> {
    if (this.isInvestigationContext(context)) {
      return this.analyzeInvestigation(context);
    }

    const investigationContext = this.createInvestigationContextFromTraffic(context);
    const result = await this.analyzeInvestigation(investigationContext);
    return this.toAnalysisResult(result);
  }

  /**
   * Get system prompt for AI model
   */
  public abstract getSystemPrompt(): string;

  /**
   * Handle analysis request message
   */
  protected async handleAnalysisRequest(message: AgentMessage): Promise<void> {
    if (this.isMessageProcessed(message.id)) {
      return;
    }
    this.markMessageProcessed(message.id);

    if (this.isOwnMessage(message)) {
      return;
    }

    const result = await this.analyzeInvestigation(message.payload);
    await this.sendMessage(message.from, 'analysis_result', {
      originalMessageId: message.id,
      result
    });
  }

  /**
   * Handle debate invitation message
   */
  protected async handleDebateInvitation(message: AgentMessage): Promise<void> {
    if (this.isMessageProcessed(message.id)) {
      return;
    }
    this.markMessageProcessed(message.id);

    if (this.isOwnMessage(message)) {
      return;
    }

    const response = {
      originalMessageId: message.id,
      accepted: true,
      agentType: this.agentType
    };
    await this.sendMessage(message.from, 'debate_argument', response);
  }

  /**
   * Handle debate argument message
   */
  protected async handleDebateArgument(message: AgentMessage): Promise<void> {
    if (this.isMessageProcessed(message.id)) {
      return;
    }
    this.markMessageProcessed(message.id);

    if (this.isOwnMessage(message)) {
      return;
    }

    const argument = await this.generateDebateArgument(message.payload);
    await this.sendMessage(message.from, 'debate_argument', {
      originalMessageId: message.id,
      argument
    });
  }

  /**
   * Handle tool result message
   */
  protected async handleToolResult(message: AgentMessage): Promise<void> {
    if (this.isMessageProcessed(message.id)) {
      return;
    }
    this.markMessageProcessed(message.id);

    if (this.isOwnMessage(message)) {
      return;
    }

    await this.processToolResult(message.payload);
  }

  /**
   * Generate debate argument - can be overridden by subclasses
   */
  protected async generateDebateArgument(payload: any): Promise<any> {
    return {
      agentType: this.agentType,
      expertise: this.expertise,
      analysis: 'Debate argument generated by base implementation'
    };
  }

  /**
   * Process tool result - can be overridden by subclasses
   */
  protected async processToolResult(payload: any): Promise<void> {
    // Default implementation - subclasses can override
  }

  /**
   * Get agent capabilities
   */
  public getCapabilities(): string[] {
    return this.expertise;
  }

  /**
   * Get agent type
   */
  public getAgentType(): InvestigationAgentType {
    return this.agentType;
  }

  /**
   * Preprocess context before analysis
   */
  protected preprocessContext(context: InvestigationContext): InvestigationContext {
    // Common preprocessing logic
    // Filter logs by timestamp range if bug report has occurrence time
    if (context.bugReport.timestamp) {
      const timeWindow = 3600000; // 1 hour window
      context.systemState.logs = context.systemState.logs.filter(log => {
        const timeDiff = Math.abs(log.timestamp.getTime() - context.bugReport.timestamp.getTime());
        return timeDiff <= timeWindow;
      });
    }

    return context;
  }

  /**
   * Extract relevant logs based on severity and service
   */
  protected extractRelevantLogs(
    logs: any[],
    severity?: string[],
    services?: string[]
  ): any[] {
    let filtered = logs;

    if (severity && severity.length > 0) {
      filtered = filtered.filter(log => severity.includes(log.level));
    }

    if (services && services.length > 0) {
      filtered = filtered.filter(log => services.includes(log.service));
    }

    return filtered.sort((a, b) => b.timestamp.getTime() - a.timestamp.getTime());
  }

  /**
   * Extract error traces
   */
  protected extractErrorTraces(traces: any[]): any[] {
    return traces.filter(trace => trace.status === 'error');
  }

  /**
   * Call AI model for analysis
   */
  protected async analyzeWithAI(
    prompt: string,
    contextData: any
  ): Promise<any> {
    try {
      const analysisPrompt = this.buildInvestigationPrompt(prompt, contextData);
      const response = await this.callModel(analysisPrompt);

      return this.parseModelResponse(response);
    } catch (error) {
      console.error(`[${this.agentType}] AI analysis failed:`, error);
      return this.fallbackAnalysis(contextData);
    }
  }

  /**
   * Build analysis prompt for AI model
   */
  protected buildInvestigationPrompt(prompt: string, contextData: any): string {
    return `
You are a specialized investigation agent for ${this.agentType}.

Your expertise includes: ${this.expertise.join(', ')}

Task: ${prompt}

Context:
${JSON.stringify(contextData, null, 2)}

Please analyze the provided context and provide:
1. Key findings
2. Potential issues or anomalies
3. Recommendations for further investigation
4. Confidence level in your analysis

Format your response as JSON.
`;
  }

  /**
   * Parse model response
   */
  protected parseModelResponse(response: ModelResponse | string): any {
    try {
      const content = typeof response === 'string' ? response : response.content;
      // Try to extract JSON from response
      const jsonMatch = content.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        return JSON.parse(jsonMatch[0]);
      }
      // If no JSON, return as text
      return { analysis: content };
    } catch (error) {
      console.error(`[${this.agentType}] Failed to parse model response:`, error);
      const content = typeof response === 'string' ? response : response.content;
      return { analysis: content, error: 'backend.failed_to_parse_response' };
    }
  }

  /**
   * Fallback analysis when AI model fails
   */
  protected fallbackAnalysis(contextData: any): any {
    return {
      findings: [],
      analysis: 'AI model unavailable, using rule-based analysis',
      confidence: 0.3,
      error: 'backend.ai_model_unavailable'
    };
  }

  /**
   * Calculate time-based correlation
   */
  protected calculateTimeCorrelation(timestamps: Date[]): any {
    if (timestamps.length < 2) {
      return { pattern: 'insufficient_data' };
    }

    const sorted = timestamps.sort((a, b) => a.getTime() - b.getTime());
    const intervals: number[] = [];

    for (let i = 1; i < sorted.length; i++) {
      intervals.push(sorted[i].getTime() - sorted[i - 1].getTime());
    }

    const avgInterval = intervals.reduce((a, b) => a + b, 0) / intervals.length;

    return {
      totalEvents: timestamps.length,
      avgInterval,
      minInterval: Math.min(...intervals),
      maxInterval: Math.max(...intervals),
      pattern: this.detectTimePattern(intervals)
    };
  }

  /**
   * Detect time patterns in intervals
   */
  private detectTimePattern(intervals: number[]): string {
    // Check for regular intervals
    const variance = this.calculateVariance(intervals);
    const avg = intervals.reduce((a, b) => a + b, 0) / intervals.length;
    const coefficientOfVariation = Math.sqrt(variance) / avg;

    if (coefficientOfVariation < 0.2) {
      return 'regular';
    } else if (coefficientOfVariation < 0.5) {
      return 'semi_regular';
    } else {
      return 'irregular';
    }
  }

  /**
   * Calculate variance
   */
  private calculateVariance(values: number[]): number {
    const avg = values.reduce((a, b) => a + b, 0) / values.length;
    return values.reduce((sum, val) => sum + Math.pow(val - avg, 2), 0) / values.length;
  }

  private isInvestigationContext(context: TrafficContext | InvestigationContext): context is InvestigationContext {
    const candidate = context as InvestigationContext;
    return !!candidate?.bugReport && !!candidate?.systemState;
  }

  private createInvestigationContextFromTraffic(context: TrafficContext): InvestigationContext {
    return {
      bugReport: {
        id: context.request.id,
        title: `${context.request.method} ${context.request.path}`,
        description: 'Traffic-derived investigation context',
        severity: 'medium',
        category: 'functional',
        environment: {
          os: 'unknown',
          runtime: 'unknown',
          version: 'unknown'
        },
        reporter: context.request.sourceIP,
        timestamp: context.request.timestamp
      },
      systemState: {
        logs: [],
        traces: [],
        metrics: {
          cpu: { usage: 0, loadAverage: [0, 0, 0] },
          memory: { used: 0, total: 0, percentage: 0 }
        },
        codeContext: undefined
      }
    };
  }

  private toAnalysisResult(result: any): AnalysisResult {
    const findings = Array.isArray(result?.findings) ? result.findings : [];
    const confidence = typeof result?.confidence === 'number' ? result.confidence : 0.5;
    const verdict = findings.some((f: any) => f?.severity === 'critical')
      ? 'malicious'
      : findings.length > 0
        ? 'suspicious'
        : 'unknown';

    return {
      agentId: this.identity.id,
      role: this.identity.role,
      verdict,
      confidence: Math.max(0, Math.min(1, confidence)),
      reasoning: typeof result?.summary === 'string'
        ? result.summary
        : 'Investigation analysis completed',
      evidence: [],
      classScores: distributionFromVerdict(verdict, Math.max(0, Math.min(1, confidence)))
    };
  }
}
