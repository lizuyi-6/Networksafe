for (const component of components) {
  if (component.screens.length !== 15) {
    throw new Error(`${component.id} must define exactly 15 screenshot sections`);
  }
  for (const [key] of component.screens) {
    if (!screenCatalog[key]) {
      throw new Error(`${component.id} references unknown screen ${key}`);
    }
  }
}

const componentCopyOwners = new Map();
for (const component of components) {
  const paragraphs = [
    ...component.overview,
    component.workflowSummary,
    ...component.workflowRows.map(([label, value]) => `${label}：${value}`),
    ...component.screens.map(([, relevance]) => relevance),
  ];
  for (const paragraph of paragraphs) {
    const normalized = paragraph.replaceAll(/\s+/g, ' ').trim();
    if (normalized.length < 20) continue;
    const existingOwner = componentCopyOwners.get(normalized);
    if (existingOwner && existingOwner !== component.id) {
      throw new Error(`Component-specific paragraph is duplicated by ${existingOwner} and ${component.id}: ${normalized}`);
    }
    componentCopyOwners.set(normalized, component.id);
  }
}
